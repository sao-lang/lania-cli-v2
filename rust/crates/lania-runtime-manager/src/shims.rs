//! Shim 生成：把 `~/.runex/shims` 里的入口转发到当前版本的二进制。
//!
//! 设计取舍：
//! - **不依赖 lania 自身的解析逻辑**：POSIX shim 只是一段 shell，运行时向
//!   `lan env which <name> --resolve` 问一次「真实路径在哪」，因此切换版本后
//!   无需重新生成也能立即生效；同时 `current` 变化会触发生成，保证新入口存在。
//! - **Windows 用 `.cmd`**：`.cmd` 会被 `cmd.exe` 与 PowerShell 正确解析，
//!   不引入额外的 Rust 二进制产物；`lan` 自身不在 PATH 时（极端情况）回退到
//!   `state.json` 里记录的绝对路径。

use std::path::{Path, PathBuf};

use anyhow::{Context, Result};

use crate::home::RuntimeHome;

/// 生成（或覆盖）一个 shim。
pub fn write_shim(home: &RuntimeHome, name: &str, version_dir: &Path) -> Result<()> {
    home.ensure_dirs()?;
    let bin_dir = home.shims_dir();
    if !entry_exists(version_dir, name) {
        return Ok(());
    }
    let binary = resolve_entry(version_dir, name);
    write_posix_shim(&bin_dir, name)?;
    #[cfg(windows)]
    write_windows_shim(&bin_dir, name, &binary)?;
    Ok(())
}

/// 在版本目录里定位某个入口的真实路径（Windows 优先 `.exe`）。
pub fn resolve_entry(version_dir: &Path, name: &str) -> String {
    let mut candidates = Vec::new();
    if cfg!(windows) {
        candidates.push(version_dir.join(format!("{name}.exe")));
        candidates.push(version_dir.join(format!("{name}.cmd")));
        candidates.push(version_dir.join(format!("{name}.bat")));
    }
    candidates.push(version_dir.join(name));
    for candidate in candidates {
        if candidate.is_file() {
            return clean_path(&candidate);
        }
    }
    clean_path(&version_dir.join(name))
}

/// 规范化展示路径：去掉 `.` 组件（`bin_dir` 为 `.` 时会拼出 `x\.\y`）。
fn clean_path(path: &Path) -> String {
    let mut out = PathBuf::new();
    for component in path.components() {
        match component {
            std::path::Component::CurDir => continue,
            other => out.push(other.as_os_str()),
        }
    }
    out.display().to_string()
}

/// 该版本目录里是否真的有这个入口（决定要不要生成 shim）。
pub fn entry_exists(version_dir: &Path, name: &str) -> bool {
    let mut candidates = vec![version_dir.join(name)];
    if cfg!(windows) {
        for extension in ["exe", "cmd", "bat"] {
            candidates.push(version_dir.join(format!("{name}.{extension}")));
        }
    }
    candidates.iter().any(|candidate| candidate.is_file())
}

fn write_posix_shim(bin_dir: &Path, name: &str) -> Result<()> {
    let path = bin_dir.join(name);
    let script = format!(
        "#!/bin/sh\n\
         # Generated by lania. Ask the current runtime pointer where `{name}` lives.\n\
         exec \"$(lan env which {name} --resolve)\" \"$@\"\n"
    );
    std::fs::write(&path, script)
        .with_context(|| format!("failed to write shim {}", path.display()))?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        let _ = std::fs::set_permissions(&path, std::fs::Permissions::from_mode(0o755));
    }
    Ok(())
}

#[cfg(windows)]
fn write_windows_shim(bin_dir: &Path, name: &str, binary: &str) -> Result<()> {
    let path = bin_dir.join(format!("{name}.cmd"));
    // 直接用绝对路径而不是再问一次 `lan env which`：Windows 上启动 `lan`
    // 每次都要过一遍 rust 二进制，`node -v` 会明显变慢。
    let body = format!(
        "@echo off\r\n\
         rem Generated by lania. Serves `{name}` of the current runtime version.\r\n\
         \"{binary}\" %*\r\n"
    );
    std::fs::write(&path, body)
        .with_context(|| format!("failed to write shim {}", path.display()))?;
    Ok(())
}

/// 删除某个入口的 shim（语言被完全卸载时调用）。
pub fn remove_shim(home: &RuntimeHome, name: &str) {
    let bin_dir = home.shims_dir();
    for path in [
        bin_dir.join(name),
        bin_dir.join(format!("{name}.cmd")),
        bin_dir.join(format!("{name}.ps1")),
    ] {
        let _ = std::fs::remove_file(path);
    }
}

/// `lan env init` 生成的 shell 片段。
pub fn shell_snippet(home: &RuntimeHome, shell: &str) -> String {
    let dir = home.display_for_shell(&home.shims_dir());
    match shell {
        "powershell" | "pwsh" => {
            format!("# Add to your PowerShell profile:\n$env:PATH = \"{dir};\" + $env:PATH\n")
        }
        "fish" => format!("# Add to ~/.config/fish/config.fish:\nfish_add_path {dir}\n"),
        _ => format!("# Add to ~/.bashrc or ~/.zshrc:\nexport PATH=\"{dir}:$PATH\"\n"),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn temp_dir(name: &str) -> std::path::PathBuf {
        let dir = std::env::temp_dir().join(format!(
            "lania-shims-{name}-{}-{:?}",
            std::process::id(),
            std::thread::current().id()
        ));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(&dir).unwrap();
        dir
    }

    #[test]
    fn resolve_entry_prefers_existing_file() {
        let dir = temp_dir("resolve");
        std::fs::write(dir.join("tool"), b"x").unwrap();
        assert!(resolve_entry(&dir, "tool").ends_with("tool"));
        // 不存在的入口返回预期路径（不 panic），便于上层给出清晰报错。
        assert!(resolve_entry(&dir, "missing").contains("missing"));
        let _ = std::fs::remove_dir_all(&dir);
    }

    #[test]
    fn writes_shim_for_existing_binary() {
        let root = temp_dir("write");
        let version_dir = root.join("runtimes").join("node").join("20.11.1");
        std::fs::create_dir_all(&version_dir).unwrap();
        std::fs::write(version_dir.join("node"), b"bin").unwrap();
        let home = RuntimeHome::at(root.join("home"));
        write_shim(&home, "node", &version_dir).unwrap();
        let shim = home.shims_dir().join("node");
        assert!(shim.is_file(), "posix shim should exist");
        let body = std::fs::read_to_string(&shim).unwrap();
        assert!(body.contains("lan env which node --resolve"));
        if cfg!(windows) {
            assert!(home.shims_dir().join("node.cmd").is_file());
            let cmd = std::fs::read_to_string(home.shims_dir().join("node.cmd")).unwrap();
            assert!(cmd.contains("node"), "{cmd}");
        }
        let _ = std::fs::remove_dir_all(&root);
    }

    #[test]
    fn shell_snippet_mentions_shims_dir() {
        let home = RuntimeHome::at(std::path::PathBuf::from("/tmp/runex"));
        let bash = shell_snippet(&home, "bash");
        assert!(
            bash.contains("/tmp/runex/shims") || bash.contains(r"\tmp\runex\shims"),
            "{bash}"
        );
        assert!(shell_snippet(&home, "powershell").contains("PATH"));
        assert!(shell_snippet(&home, "fish").contains("fish_add_path"));
    }
}
