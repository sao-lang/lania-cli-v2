#!/usr/bin/env node
/**
 * Bridge Hub 帧协议生成器 —— 唯一事实源 schema.json。
 *
 *   node packages/products/bridge-hub/protocol/gen.mjs            生成 5 语言绑定 + 端点骨架 + golden
 *   node packages/products/bridge-hub/protocol/gen.mjs --check     校验生成物未漂移（CI 用，按 LF 归一化）
 *
 * 无第三方依赖。生成物禁止手改：
 *   - protocol.*  : 帧类型 / 编解码 / 错误码 / 帧构造函数
 *   - runtime.*   : 传输循环 / correlation id / pending / 心跳 / 错误包装 / boot
 * 手写 adaptor 只允许提供 manifest + onRequest/onEvent 两个回调。
 */
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = 'packages/products/bridge-hub/protocol/schema.json';
const schema = JSON.parse(readFileSync(join(HERE, 'schema.json'), 'utf8'));
const CHECK = process.argv.includes('--check');

const BANNER = {
  rust: '// GENERATED BY ' + SOURCE.replace('schema.json', 'gen.mjs') + ' — DO NOT EDIT\n// Source: ' + SOURCE + '\n\n',
  ts: '// GENERATED BY ' + SOURCE.replace('schema.json', 'gen.mjs') + ' — DO NOT EDIT\n// Source: ' + SOURCE + '\n\n',
  py: '# GENERATED BY ' + SOURCE.replace('schema.json', 'gen.mjs') + ' — DO NOT EDIT\n# Source: ' + SOURCE + '\n\n',
  go: '// GENERATED BY ' + SOURCE.replace('schema.json', 'gen.mjs') + ' — DO NOT EDIT\n// Source: ' + SOURCE + '\n\n',
  dart: '// GENERATED BY ' + SOURCE.replace('schema.json', 'gen.mjs') + ' — DO NOT EDIT\n// Source: ' + SOURCE + '\n\n',
};

const q = (s) => JSON.stringify(s);
const words = (s) => s.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_+|_+$/g, '').split('_').filter(Boolean);
const pascal = (s) => words(s).map((w) => w[0].toUpperCase() + w.slice(1)).join('');
const camel = (s) => { const p = pascal(s); return p[0].toLowerCase() + p.slice(1); };
const snake = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1_$2').replace(/[^a-zA-Z0-9]+/g, '_').toLowerCase();
const PY_RESERVED = new Set(['from', 'class', 'def', 'global', 'import', 'pass', 'return', 'yield', 'in', 'is', 'lambda', 'None', 'True', 'False']);
const pyName = (n) => { const base = snake(n); return PY_RESERVED.has(base) ? base + '_' : base; };
const constName = (s) => s.replace(/[^a-zA-Z0-9]+/g, '_').replace(/^_+|_+$/g, '').toUpperCase();
const stripOpt = (t) => (t.endsWith('?') ? t.slice(0, -1) : t);
const isOpt = (t) => t.endsWith('?');
const isArray = (t) => stripOpt(t).endsWith('[]');
const elem = (t) => { const base = stripOpt(t); return isArray(t) ? base.slice(0, -2) : base; };
const dartConstName = (s) => {
  const p = s.split('_').map((w) => w[0].toUpperCase() + w.slice(1).toLowerCase()).join('');
  return p[0].toLowerCase() + p.slice(1);
};

const rustType = (t) => {
  const map = { string: 'String', value: 'Value', error: 'BusErrorDetail' };
  let r = map[elem(t)] ?? 'Value';
  if (isArray(t)) r = 'Vec<' + r + '>';
  return isOpt(t) ? 'Option<' + r + '>' : r;
};
const tsType = (t) => {
  const map = { string: 'string', value: 'Value', error: 'BusErrorDetail' };
  let r = map[elem(t)] ?? 'Value';
  if (isArray(t)) r = r + '[]';
  return r;
};
const pyType = (t) => {
  const map = { string: 'str', value: 'Any', error: 'dict' };
  let r = map[elem(t)] ?? 'Any';
  if (isArray(t)) r = 'list[' + r + ']';
  return r;
};
const goType = (t) => {
  const map = { string: 'string', value: 'json.RawMessage', error: '*BusErrorDetail' };
  let r = map[elem(t)] ?? 'json.RawMessage';
  if (isArray(t)) r = '[]' + r;
  return r;
};
const dartType = (t) => {
  const map = { string: 'String', value: 'dynamic', error: 'Map<String, dynamic>?' };
  let r = map[elem(t)] ?? 'dynamic';
  if (isArray(t)) r = 'List<' + r + '>';
  return r;
};

const kinds = schema.frames.map((f) => f.kind);
const errors = schema.errors.map((e) => e.code);
const frameHelpers = schema.frames.map((f) => camel(f.kind) + 'Frame');
const generatedFiles = [];

function emit(rel, content) {
  generatedFiles.push({ rel, content: content.replace(/\r\n/g, '\n') });
}

// ------------------------------------------------------------------ Rust protocol
function rustProtocol() {
  const errConsts = errors.map((c) => 'pub const ' + constName(c) + ': &str = ' + q(c) + ';').join('\n');
  const variants = schema.frames.map((f) => {
    const fields = f.fields.map((fld) => {
      const attrs = [];
      if (snake(fld.name) !== fld.name) attrs.push('        #[serde(rename = ' + q(fld.name) + ')]');
      if (isOpt(fld.type)) attrs.push('        #[serde(skip_serializing_if = "Option::is_none")]');
      // 其它语言的生成物可能省略 null/空数组字段，Rust 侧给 Value/Vec 兜底默认值。
      if (elem(fld.type) === 'value' || isArray(fld.type)) attrs.push('        #[serde(default)]');
      return attrs.join('\n') + (attrs.length ? '\n' : '') + '        ' + snake(fld.name) + ': ' + rustType(fld.type) + ',';
    }).join('\n');
    return '    ' + pascal(f.kind) + ' {\n' + fields + '\n    },';
  }).join('\n');
  const kindArms = schema.frames.map((f) => '            Self::' + pascal(f.kind) + ' { .. } => ' + q(f.kind) + ',').join('\n');
  return BANNER.rust +
    'pub use serde_json::Value;\n' +
    'use serde::{Deserialize, Serialize};\n\n' +
    'pub const FRAME_KINDS: &[&str] = &[\n' + kinds.map((k) => '    ' + q(k) + ',').join('\n') + '\n];\n\n' +
    errConsts + '\n\n' +
    '#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]\n' +
    'pub struct BusErrorDetail {\n' +
    '    pub code: String,\n' +
    '    pub message: String,\n' +
    '    #[serde(skip_serializing_if = "Option::is_none")]\n' +
    '    pub data: Option<Value>,\n' +
    '}\n\n' +
    '#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]\n' +
    '#[serde(tag = ' + q(schema.discriminator) + ', rename_all = "lowercase")]\n' +
    'pub enum BusFrame {\n' + variants + '\n}\n\n' +
    'impl BusFrame {\n' +
    '    pub fn kind(&self) -> &\'static str {\n' +
    '        match self {\n' + kindArms + '\n        }\n' +
    '    }\n' +
    '}\n\n' +
    'pub fn encode_frame(frame: &BusFrame) -> Result<String, serde_json::Error> {\n' +
    '    serde_json::to_string(frame)\n' +
    '}\n\n' +
    'pub fn decode_frame(line: &str) -> Result<BusFrame, serde_json::Error> {\n' +
    '    serde_json::from_str(line)\n' +
    '}\n\n' +
    'pub fn bus_error(code: &str, message: impl Into<String>) -> BusErrorDetail {\n' +
    '    BusErrorDetail { code: code.to_string(), message: message.into(), data: None }\n' +
    '}\n';
}

// ------------------------------------------------------------------ Rust runtime
function rustRuntime() {
  return BANNER.rust +
    'use lania_bridge_protocol::{bus_error, BusErrorDetail, BusFrame, Value, E_INTERNAL};\n\n' +
    '/// 端点骨架：correlation id、帧构造、错误包装。传输由 Channel 完成。\n' +
    'pub struct EndpointRuntime<S> {\n' +
    '    endpoint_id: String,\n' +
    '    next_id: u64,\n' +
    '    sink: S,\n' +
    '}\n\n' +
    'impl<S> EndpointRuntime<S>\nwhere\n    S: FnMut(BusFrame),\n{\n' +
    '    pub fn new(endpoint_id: impl Into<String>, sink: S) -> Self {\n' +
    '        Self { endpoint_id: endpoint_id.into(), next_id: 0, sink }\n' +
    '    }\n\n' +
    '    pub fn endpoint_id(&self) -> &str { &self.endpoint_id }\n\n' +
    '    pub fn announce(&mut self, provides: Vec<String>, subscribes: Vec<String>) {\n' +
    '        let id = self.endpoint_id.clone();\n' +
    '        self.emit(BusFrame::Announce { endpoint_id: id, provides, subscribes });\n' +
    '    }\n\n' +
    '    pub fn subscribe(&mut self, topic: &str) {\n' +
    '        self.emit(BusFrame::Subscribe { topic: topic.to_string() });\n' +
    '    }\n\n' +
    '    pub fn unsubscribe(&mut self, topic: &str) {\n' +
    '        self.emit(BusFrame::Unsubscribe { topic: topic.to_string() });\n' +
    '    }\n\n' +
    '    pub fn publish(&mut self, topic: &str, payload: Value) {\n' +
    '        self.emit(BusFrame::Publish { topic: topic.to_string(), payload });\n' +
    '    }\n\n' +
    '    pub fn request(&mut self, capability: &str, params: Value) -> String {\n' +
    '        let id = self.correlation_id();\n' +
    '        self.emit(BusFrame::Request {\n' +
    '            id: id.clone(),\n' +
    '            capability: capability.to_string(),\n' +
    '            params,\n' +
    '        });\n' +
    '        id\n' +
    '    }\n\n' +
    '    pub fn respond(&mut self, id: String, outcome: Result<Value, BusErrorDetail>) {\n' +
    '        let (result, error) = match outcome {\n' +
    '            Ok(value) => (Some(value), None),\n' +
    '            Err(err) => (None, Some(err)),\n' +
    '        };\n' +
    '        self.emit(BusFrame::Response { id, result, error });\n' +
    '    }\n\n' +
    '    /// 业务回调抛错时的统一包装（错误包装由生成器负责）。\n' +
    '    pub fn wrap_internal(&self, err: impl std::fmt::Display) -> BusErrorDetail {\n' +
    '        bus_error(E_INTERNAL, err.to_string())\n' +
    '    }\n\n' +
    '    pub fn heartbeat(&mut self) {\n' +
    '        let id = self.endpoint_id.clone();\n' +
    '        self.emit(BusFrame::Publish {\n' +
    '            topic: "event.heartbeat".to_string(),\n' +
    '            payload: serde_json::json!({ "endpointId": id }),\n' +
    '        });\n' +
    '    }\n\n' +
    '    pub fn bye(&mut self) {\n' +
    '        let id = self.endpoint_id.clone();\n' +
    '        self.emit(BusFrame::Bye { endpoint_id: id });\n' +
    '    }\n\n' +
    '    fn correlation_id(&mut self) -> String {\n' +
    '        self.next_id += 1;\n' +
    '        format!("{}-{}", self.endpoint_id, self.next_id)\n' +
    '    }\n\n' +
    '    fn emit(&mut self, frame: BusFrame) { (self.sink)(frame); }\n' +
    '}\n';
}

// ------------------------------------------------------------------ TypeScript protocol
function tsProtocol() {
  const errConsts = errors.map((c) => 'export const ' + constName(c) + ' = ' + q(c) + ';').join('\n');
  const variants = schema.frames.map((f) => {
    const fields = f.fields.map((fld) => {
      const opt = isOpt(fld.type) ? '?' : '';
      return '  ' + fld.name + opt + ': ' + tsType(fld.type) + ';';
    }).join('\n');
    return '  | { kind: ' + q(f.kind) + ';\n' + fields + '\n    }';
  }).join('\n');
  const helpers = schema.frames.map((f) => {
    const args = f.fields.map((fld) => fld.name + (isOpt(fld.type) ? '?' : '') + ': ' + tsType(fld.type)).join(', ');
    const body = f.fields.map((fld) => {
      if (!isOpt(fld.type)) return '    ' + fld.name + ',';
      return '    ...(' + fld.name + ' === undefined ? {} : { ' + fld.name + ' }),';
    }).join('\n');
    return 'export function ' + camel(f.kind) + 'Frame(' + args + '): BusFrame {\n' +
      '  return { kind: ' + q(f.kind) + ',\n' + body + '\n  };\n' +
      '}\n';
  }).join('\n');
  return BANNER.ts +
    'export type Value = any;\n\n' +
    'export interface BusErrorDetail { code: string; message: string; data?: Value }\n\n' +
    'export const FRAME_KINDS: readonly string[] = [' + kinds.map(q).join(', ') + '];\n\n' +
    errConsts + '\n\n' +
    'export type BusFrame =\n' + variants + ';\n\n' +
    'export function busError(code: string, message: string, data?: Value): BusErrorDetail {\n' +
    '  return data === undefined ? { code, message } : { code, message, data };\n' +
    '}\n\n' +
    'export function encodeFrame(frame: BusFrame): string { return JSON.stringify(frame); }\n\n' +
    'export function decodeFrame(line: string): BusFrame {\n' +
    '  const raw = JSON.parse(line) as Record<string, unknown>;\n' +
    '  if (typeof raw !== "object" || raw === null || !FRAME_KINDS.includes(raw.kind as string)) {\n' +
    '    throw new Error("E_BAD_FRAME");\n' +
    '  }\n' +
    '  return raw as unknown as BusFrame;\n' +
    '}\n\n' +
    helpers;
}

// ------------------------------------------------------------------ TypeScript runtime
function tsRuntime() {
  const imports = ['E_INTERNAL', 'busError', 'decodeFrame', 'encodeFrame'].concat(frameHelpers).join(', ');
  return BANNER.ts +
    "import { createInterface } from 'node:readline';\n" +
    "import type { BusErrorDetail, BusFrame, Value } from './protocol.ts';\n" +
    "import { " + imports + " } from './protocol.ts';\n\n" +
    'export interface EndpointManifest { provides: string[]; subscribes: string[] }\n' +
    'export interface RequestOutcome { result?: Value; error?: BusErrorDetail }\n' +
    'export interface EndpointHooks {\n' +
    '  onRequest(capability: string, params: Value, correlationId: string): RequestOutcome | Value | Promise<RequestOutcome | Value>;\n' +
    '  onEvent(topic: string, payload: Value, from: string): void;\n' +
    '}\n\n' +
    'type Pending = { resolve: (value: Value) => void; reject: (err: BusErrorDetail) => void };\n\n' +
    'let activeRuntime: EndpointRuntime | null = null;\n' +
    'export function currentRuntime(): EndpointRuntime {\n' +
    '  if (!activeRuntime) throw new Error("endpoint runtime is not started");\n' +
    '  return activeRuntime;\n' +
    '}\n\n' +
    'export class EndpointRuntime {\n' +
    '  private readonly endpointId: string;\n' +
    '  private readonly hooks: EndpointHooks;\n' +
    '  private counter = 0;\n' +
    '  private readonly pending = new Map<string, Pending>();\n\n' +
    '  constructor(endpointId: string, hooks: EndpointHooks) {\n' +
    '    this.endpointId = endpointId;\n' +
    '    this.hooks = hooks;\n' +
    '  }\n\n' +
    '  announce(provides: string[], subscribes: string[]): void {\n' +
    '    this.write(announceFrame(this.endpointId, provides, subscribes));\n' +
    '  }\n' +
    '  subscribe(topic: string): void { this.write(subscribeFrame(topic)); }\n' +
    '  unsubscribe(topic: string): void { this.write(unsubscribeFrame(topic)); }\n' +
    '  publish(topic: string, payload: Value): void { this.write(publishFrame(topic, payload)); }\n' +
    '  bye(): void { this.write(byeFrame(this.endpointId)); }\n' +
    '  heartbeat(): void { this.write(publishFrame("event.heartbeat", { endpointId: this.endpointId })); }\n\n' +
    '  request(capability: string, params: Value): Promise<Value> {\n' +
    '    const id = this.correlationId();\n' +
    '    return new Promise<Value>((resolve, reject) => {\n' +
    '      this.pending.set(id, { resolve, reject });\n' +
    '      this.write(requestFrame(id, capability, params));\n' +
    '    });\n' +
    '  }\n\n' +
    '  write(frame: BusFrame): void { process.stdout.write(encodeFrame(frame) + "\\n"); }\n\n' +
    '  handle(line: string): void {\n' +
    '    let frame: BusFrame;\n' +
    '    try { frame = decodeFrame(line); } catch { return; }\n' +
    '    if (frame.kind === "request") { void this.serveRequest(frame); return; }\n' +
    '    if (frame.kind === "event") { this.hooks.onEvent(frame.topic, frame.payload, frame.from); return; }\n' +
    '    if (frame.kind === "response") {\n' +
    '      const entry = this.pending.get(frame.id);\n' +
    '      if (!entry) return;\n' +
    '      this.pending.delete(frame.id);\n' +
    '      if (frame.error) entry.reject(frame.error); else entry.resolve(frame.result ?? null);\n' +
    '    }\n' +
    '  }\n\n' +
    '  private async serveRequest(frame: Extract<BusFrame, { kind: "request" }>): Promise<void> {\n' +
    '    try {\n' +
    '      const raw = await this.hooks.onRequest(frame.capability, frame.params, frame.id);\n' +
    '      const outcome = (raw !== null && typeof raw === "object" && ("result" in raw || "error" in raw))\n' +
    '        ? raw as RequestOutcome : { result: raw };\n' +
    '      this.write(responseFrame(frame.id, outcome.result, outcome.error));\n' +
    '    } catch (err) {\n' +
    '      this.write(responseFrame(frame.id, undefined, busError(E_INTERNAL, String(err))));\n' +
    '    }\n' +
    '  }\n\n' +
    '  private correlationId(): string { this.counter += 1; return this.endpointId + "-" + this.counter; }\n\n' +
    '  async run(): Promise<void> {\n' +
    '    const lines = createInterface({ input: process.stdin, crlfDelay: Infinity });\n' +
    '    for await (const line of lines) this.handle(line);\n' +
    '  }\n' +
    '}\n\n' +
    'export function endpointIdFromEnv(): string {\n' +
    '  const arg = process.argv.find((a) => a.startsWith("--endpoint-id="));\n' +
    '  return arg ? arg.slice("--endpoint-id=".length) : (process.env.LANIA_ENDPOINT_ID ?? "endpoint-" + process.pid);\n' +
    '}\n\n' +
    'export async function boot(manifest: EndpointManifest, hooks: EndpointHooks): Promise<void> {\n' +
    '  const runtime = new EndpointRuntime(endpointIdFromEnv(), hooks);\n' +
    '  activeRuntime = runtime;\n' +
    '  runtime.announce(manifest.provides, manifest.subscribes);\n' +
    '  const interval = Number(process.env.LANIA_BRIDGE_HEARTBEAT_MS ?? 0);\n' +
    '  if (interval > 0) {\n' +
    '    const timer = setInterval(() => runtime.heartbeat(), interval);\n' +
    '    (timer as any).unref?.();\n' +
    '  }\n' +
    '  try { await runtime.run(); } finally { runtime.bye(); }\n' +
    '}\n';
}

// ------------------------------------------------------------------ Python protocol
function pyProtocol() {
  const errConsts = errors.map((c) => constName(c) + ' = ' + q(c)).join('\n');
  const helpers = schema.frames.map((f) => {
    const args = f.fields.map((fld) => pyName(fld.name) + (isOpt(fld.type) ? ' = None' : '')).join(', ');
    const body = f.fields.map((fld) => {
      const key = fld.name;
      const varName = pyName(fld.name);
      if (!isOpt(fld.type)) return '        ' + q(key) + ': ' + varName + ',';
      return '        **({' + q(key) + ': ' + varName + '} if ' + varName + ' is not None else {}),';
    }).join('\n');
    return 'def ' + snake(f.kind) + '_frame(' + args + '):\n' +
      '    return {\n        ' + q('kind') + ': ' + q(f.kind) + ',\n' + body + '\n    }\n';
  }).join('\n\n');
  return BANNER.py +
    'from __future__ import annotations\n\n' +
    'import json\n' +
    'from typing import Any\n\n' +
    'FRAME_KINDS = [' + kinds.map(q).join(', ') + ']\n\n' +
    errConsts + '\n\n' +
    'def bus_error(code: str, message: str, data: Any = None) -> dict:\n' +
    '    detail = {"code": code, "message": message}\n' +
    '    if data is not None:\n' +
    '        detail["data"] = data\n' +
    '    return detail\n\n\n' +
    'def encode_frame(frame: dict) -> str:\n' +
    '    return json.dumps(frame, ensure_ascii=False, separators=(",", ":"))\n\n\n' +
    'def decode_frame(line: str) -> dict:\n' +
    '    frame = json.loads(line)\n' +
    '    if not isinstance(frame, dict) or frame.get("kind") not in FRAME_KINDS:\n' +
    '        raise ValueError("E_BAD_FRAME")\n' +
    '    return frame\n\n\n' +
    helpers + '\n';
}

// ------------------------------------------------------------------ Python runtime
function pyRuntime() {
  const imports = ['E_INTERNAL', 'bus_error', 'decode_frame', 'encode_frame'].concat(schema.frames.map((f) => snake(f.kind) + '_frame')).join(', ');
  return BANNER.py +
    'from __future__ import annotations\n\n' +
    'import os\n' +
    'import sys\n' +
    'import threading\n' +
    'from concurrent.futures import Future\n' +
    'from typing import Any, Callable\n\n' +
    'from lania_bridge_protocol import (\n    ' + imports + ',\n)\n\n' +
    'active_runtime = None\n\n\n' +
    'def current_runtime():\n' +
    '    if active_runtime is None:\n' +
    '        raise RuntimeError("endpoint runtime is not started")\n' +
    '    return active_runtime\n\n\n' +
    'class EndpointRuntime:\n' +
    '    """端点骨架：stdio 帧循环 / id / pending / 心跳 / 错误包装。"""\n\n' +
    '    def __init__(self, endpoint_id: str, hooks: Any) -> None:\n' +
    '        self.endpoint_id = endpoint_id\n' +
    '        self.hooks = hooks\n' +
    '        self.counter = 0\n' +
    '        self.pending: dict[str, Future] = {}\n' +
    '        self.lock = threading.Lock()\n\n' +
    '    def write(self, frame: dict) -> None:\n' +
    '        with self.lock:\n' +
    '            sys.stdout.write(encode_frame(frame) + "\\n")\n' +
    '            sys.stdout.flush()\n\n' +
    '    def announce(self, provides: list[str], subscribes: list[str]) -> None:\n' +
    '        self.write(announce_frame(self.endpoint_id, provides, subscribes))\n\n' +
    '    def subscribe(self, topic: str) -> None: self.write(subscribe_frame(topic))\n' +
    '    def unsubscribe(self, topic: str) -> None: self.write(unsubscribe_frame(topic))\n' +
    '    def publish(self, topic: str, payload: Any) -> None: self.write(publish_frame(topic, payload))\n' +
    '    def bye(self) -> None: self.write(bye_frame(self.endpoint_id))\n' +
    '    def heartbeat(self) -> None: self.write(publish_frame("event.heartbeat", {"endpointId": self.endpoint_id}))\n\n' +
    '    def request(self, capability: str, params: Any, on_response: Callable | None = None) -> Future:\n' +
    '        correlation_id = self._correlation_id()\n' +
    '        future: Future = Future()\n' +
    '        if on_response is not None:\n' +
    '            future.add_done_callback(lambda f: on_response(f.result() if not f.exception() else None, f.exception()))\n' +
    '        with self.lock:\n' +
    '            self.pending[correlation_id] = future\n' +
    '        self.write(request_frame(correlation_id, capability, params))\n' +
    '        return future\n\n' +
    '    def handle(self, line: str) -> None:\n' +
    '        try:\n' +
    '            frame = decode_frame(line)\n' +
    '        except Exception:\n' +
    '            return\n' +
    '        kind = frame["kind"]\n' +
    '        if kind == "request":\n' +
    '            self._serve(frame)\n' +
    '        elif kind == "event":\n' +
    '            self.hooks.on_event(frame["topic"], frame.get("payload"), frame["from"])\n' +
    '        elif kind == "response":\n' +
    '            with self.lock:\n' +
    '                future = self.pending.pop(frame["id"], None)\n' +
    '            if future is not None and not future.done():\n' +
    '                if frame.get("error"):\n' +
    '                    detail = frame["error"]\n' +
    '                    future.set_exception(RuntimeError(detail.get("code", "E_INTERNAL") + ": " + detail.get("message", "")))\n' +
    '                else:\n' +
    '                    future.set_result(frame.get("result"))\n\n' +
    '    def _serve(self, frame: dict) -> None:\n' +
    '        try:\n' +
    '            raw = self.hooks.on_request(frame["capability"], frame.get("params"), frame["id"])\n' +
    '            if isinstance(raw, dict) and ("result" in raw or "error" in raw):\n' +
    '                result, error = raw.get("result"), raw.get("error")\n' +
    '            else:\n' +
    '                result, error = raw, None\n' +
    '            self.write(response_frame(frame["id"], result, error))\n' +
    '        except Exception as exc:\n' +
    '            self.write(response_frame(frame["id"], None, bus_error(E_INTERNAL, str(exc))))\n\n' +
    '    def _correlation_id(self) -> str:\n' +
    '        self.counter += 1\n' +
    '        return self.endpoint_id + "-" + str(self.counter)\n\n' +
    '    def run(self) -> None:\n' +
    '        for line in sys.stdin:\n' +
    '            self.handle(line)\n\n\n' +
    'def endpoint_id_from_env() -> str:\n' +
    '    for arg in sys.argv[1:]:\n' +
    '        if arg.startswith("--endpoint-id="):\n' +
    '            return arg.split("=", 1)[1]\n' +
    '    return os.environ.get("LANIA_ENDPOINT_ID", "endpoint-" + str(os.getpid()))\n\n\n' +
    'def boot(manifest: dict, hooks: Any) -> None:\n' +
    '    global active_runtime\n' +
    '    runtime = EndpointRuntime(endpoint_id_from_env(), hooks)\n' +
    '    active_runtime = runtime\n' +
    '    runtime.announce(manifest["provides"], manifest["subscribes"])\n' +
    '    interval = int(os.environ.get("LANIA_BRIDGE_HEARTBEAT_MS", "0") or 0)\n' +
    '    if interval > 0:\n' +
    '        def tick() -> None:\n' +
    '            runtime.heartbeat()\n' +
    '            timer = threading.Timer(interval / 1000.0, tick)\n' +
    '            timer.daemon = True\n' +
    '            timer.start()\n' +
    '        threading.Thread(target=tick, daemon=True).start()\n' +
    '    try:\n' +
    '        runtime.run()\n' +
    '    finally:\n' +
    '        runtime.bye()\n';
}

// ------------------------------------------------------------------ Go protocol
function goProtocol() {
  const errConsts = errors.map((c) => '\t' + constName(c) + ' = ' + q(c)).join('\n');
  const fields = [...new Set(schema.frames.flatMap((f) => f.fields.map((x) => x.name)))];
  const goFieldName = (n) => n === 'endpointId' ? 'EndpointID' : n === 'id' ? 'ID' : pascal(n);
  const structFields = fields.map((n) => {
    const fld = schema.frames.flatMap((f) => f.fields).find((x) => x.name === n);
    const optional = fld && isOpt(fld.type);
    const typ = optional ? (n === 'result' ? '*json.RawMessage' : '*BusErrorDetail') : goType(fld.type);
    return '\t' + goFieldName(n) + ' ' + typ + ' \x60json:"' + n + ',omitempty"\x60';
  }).join('\n');
  const helpers = schema.frames.map((f) => {
    const args = f.fields.map((fld) => snake(fld.name) + ' ' + (isOpt(fld.type) ? (fld.name === 'result' ? '*json.RawMessage' : '*BusErrorDetail') : goType(fld.type))).join(', ');
    const body = f.fields.map((fld) => '\t\t' + goFieldName(fld.name) + ': ' + snake(fld.name) + ',').join('\n');
    return 'func ' + camel(f.kind) + 'Frame(' + args + ') BusFrame {\n' +
      '\treturn BusFrame{\n\t\tKind: ' + q(f.kind) + ',\n' + body + '\n\t}\n}\n';
  }).join('\n');
  return BANNER.go +
    'package main\n\n' +
    'import (\n\t"encoding/json"\n\t"fmt"\n)\n\n' +
    'var FRAME_KINDS = []string{' + kinds.map(q).join(', ') + '}\n\n' +
    'const (\n' + errConsts + '\n)\n\n' +
    'type BusErrorDetail struct {\n' +
    '\tCode string \x60json:"code"\x60\n' +
    '\tMessage string \x60json:"message"\x60\n' +
    '\tData any \x60json:"data,omitempty"\x60\n' +
    '}\n\n' +
    'type BusFrame struct {\n' +
    '\tKind string \x60json:"kind"\x60\n' +
    structFields + '\n}\n\n' +
    'func BusError(code string, message string) *BusErrorDetail {\n' +
    '\treturn &BusErrorDetail{Code: code, Message: message}\n' +
    '}\n\n' +
    'func EncodeFrame(frame BusFrame) (string, error) {\n' +
    '\tdata, err := json.Marshal(frame)\n' +
    '\treturn string(data), err\n' +
    '}\n\n' +
    'func DecodeFrame(line string) (BusFrame, error) {\n' +
    '\tvar frame BusFrame\n' +
    '\tif err := json.Unmarshal([]byte(line), &frame); err != nil {\n' +
    '\t\treturn frame, err\n' +
    '\t}\n' +
    '\tvalid := false\n' +
    '\tfor _, kind := range FRAME_KINDS {\n' +
    '\t\tif frame.Kind == kind { valid = true; break }\n' +
    '\t}\n' +
    '\tif !valid { return frame, fmt.Errorf("E_BAD_FRAME: %s", frame.Kind) }\n' +
    '\treturn frame, nil\n' +
    '}\n\n' +
    helpers;
}

// ------------------------------------------------------------------ Go runtime
function goRuntime() {
  return BANNER.go +
    'package main\n\n' +
    'import (\n' +
    '\t"bufio"\n\t"encoding/json"\n\t"fmt"\n\t"os"\n\t"strconv"\n\t"strings"\n\t"sync"\n\t"time"\n' +
    ')\n\n' +
    'type EndpointManifest struct {\n\tProvides []string\n\tSubscribes []string\n}\n\n' +
    'type RequestOutcome struct {\n\tResult any\n\tError *BusErrorDetail\n}\n\n' +
    'type EndpointHooks struct {\n' +
    '\tOnRequest func(capability string, params json.RawMessage, correlationID string) RequestOutcome\n' +
    '\tOnEvent func(topic string, payload json.RawMessage, from string)\n' +
    '}\n\n' +
    'var activeRuntime *EndpointRuntime\n\n' +
    'func CurrentRuntime() *EndpointRuntime {\n' +
    '\tif activeRuntime == nil { panic("endpoint runtime is not started") }\n' +
    '\treturn activeRuntime\n' +
    '}\n\n' +
    'type EndpointRuntime struct {\n' +
    '\tendpointID string\n' +
    '\thooks EndpointHooks\n' +
    '\tmu sync.Mutex\n' +
    '\tcounter uint64\n' +
    '\tpending map[string]func(any, *BusErrorDetail)\n' +
    '\tout *bufio.Writer\n' +
    '}\n\n' +
    'func NewEndpointRuntime(endpointID string, hooks EndpointHooks) *EndpointRuntime {\n' +
    '\treturn &EndpointRuntime{endpointID: endpointID, hooks: hooks, pending: map[string]func(any, *BusErrorDetail){}, out: bufio.NewWriter(os.Stdout)}\n' +
    '}\n\n' +
    'func (r *EndpointRuntime) Write(frame BusFrame) {\n' +
    '\tline, err := EncodeFrame(frame)\n' +
    '\tif err != nil { return }\n' +
    '\tr.mu.Lock()\n' +
    '\tdefer r.mu.Unlock()\n' +
    '\tfmt.Fprintln(r.out, line)\n' +
    '\tr.out.Flush()\n' +
    '}\n\n' +
    'func (r *EndpointRuntime) Announce(provides []string, subscribes []string) {\n' +
    '\tr.Write(announceFrame(r.endpointID, provides, subscribes))\n' +
    '}\n' +
    'func (r *EndpointRuntime) Subscribe(topic string) { r.Write(subscribeFrame(topic)) }\n' +
    'func (r *EndpointRuntime) Unsubscribe(topic string) { r.Write(unsubscribeFrame(topic)) }\n' +
    'func (r *EndpointRuntime) Publish(topic string, payload json.RawMessage) { r.Write(publishFrame(topic, payload)) }\n' +
    'func (r *EndpointRuntime) Bye() { r.Write(byeFrame(r.endpointID)) }\n' +
    'func (r *EndpointRuntime) Heartbeat() { r.Write(publishFrame("event.heartbeat", json.RawMessage("{\\"endpointId\\":\\"" + r.endpointID + "\\"}"))) }\n\n' +
    'func (r *EndpointRuntime) Request(capability string, params json.RawMessage, cb func(any, *BusErrorDetail)) string {\n' +
    '\tr.mu.Lock()\n' +
    '\tr.counter++\n' +
    '\tid := r.endpointID + "-" + strconv.FormatUint(r.counter, 10)\n' +
    '\tr.pending[id] = cb\n' +
    '\tr.mu.Unlock()\n' +
    '\tr.Write(requestFrame(id, capability, params))\n' +
    '\treturn id\n' +
    '}\n\n' +
    'func (r *EndpointRuntime) Handle(line string) {\n' +
    '\tframe, err := DecodeFrame(line)\n' +
    '\tif err != nil { return }\n' +
    '\tswitch frame.Kind {\n' +
    '\tcase "request":\n' +
    '\t\toutcome := r.hooks.OnRequest(frame.Capability, frame.Params, frame.ID)\n' +
    '\t\tvar result *json.RawMessage\n' +
    '\t\tif outcome.Result != nil {\n' +
    '\t\t\tdata, err := json.Marshal(outcome.Result)\n' +
    '\t\t\tif err == nil { raw := json.RawMessage(data); result = &raw }\n' +
    '\t\t}\n' +
    '\t\tr.Write(responseFrame(frame.ID, result, outcome.Error))\n' +
    '\tcase "event":\n' +
    '\t\tif r.hooks.OnEvent != nil { r.hooks.OnEvent(frame.Topic, frame.Payload, frame.From) }\n' +
    '\tcase "response":\n' +
    '\t\tr.mu.Lock()\n' +
    '\t\tcb := r.pending[frame.ID]\n' +
    '\t\tdelete(r.pending, frame.ID)\n' +
    '\t\tr.mu.Unlock()\n' +
    '\t\tif cb != nil {\n' +
    '\t\t\tif frame.Error != nil { cb(nil, frame.Error) } else if frame.Result != nil { cb(json.RawMessage(*frame.Result), nil) } else { cb(nil, nil) }\n' +
    '\t\t}\n' +
    '\t}\n' +
    '}\n\n' +
    'func (r *EndpointRuntime) Run() {\n' +
    '\tscanner := bufio.NewScanner(os.Stdin)\n' +
    '\tscanner.Buffer(make([]byte, 1024), 4*1024*1024)\n' +
    '\tfor scanner.Scan() { r.Handle(scanner.Text()) }\n' +
    '}\n\n' +
    'func EndpointIDFromEnv() string {\n' +
    '\tfor _, arg := range os.Args[1:] {\n' +
    '\t\tif strings.HasPrefix(arg, "--endpoint-id=") { return strings.TrimPrefix(arg, "--endpoint-id=") }\n' +
    '\t}\n' +
    '\tif id := os.Getenv("LANIA_ENDPOINT_ID"); id != "" { return id }\n' +
    '\treturn "endpoint-" + strconv.Itoa(os.Getpid())\n' +
    '}\n\n' +
    'func Boot(manifest EndpointManifest, hooks EndpointHooks) {\n' +
    '\truntime := NewEndpointRuntime(EndpointIDFromEnv(), hooks)\n' +
    '\tactiveRuntime = runtime\n' +
    '\truntime.Announce(manifest.Provides, manifest.Subscribes)\n' +
    '\tif raw := os.Getenv("LANIA_BRIDGE_HEARTBEAT_MS"); raw != "" {\n' +
    '\t\tif ms, err := strconv.Atoi(raw); err == nil && ms > 0 {\n' +
    '\t\t\tgo func() {\n' +
    '\t\t\t\tticker := time.NewTicker(time.Duration(ms) * time.Millisecond)\n' +
    '\t\t\t\tdefer ticker.Stop()\n' +
    '\t\t\t\tfor range ticker.C { runtime.Heartbeat() }\n' +
    '\t\t\t}()\n' +
    '\t\t}\n' +
    '\t}\n' +
    '\tdefer runtime.Bye()\n' +
    '\truntime.Run()\n' +
    '}\n';
}

// ------------------------------------------------------------------ Dart protocol
function dartProtocol() {
  const errConsts = errors.map((c) => 'const String ' + dartConstName(c) + ' = ' + q(c) + ';').join('\n');
  const fields = [...new Set(schema.frames.flatMap((f) => f.fields.map((x) => x.name)))];
  const decls = fields.map((n) => {
    const fld = schema.frames.flatMap((f) => f.fields).find((x) => x.name === n);
    const type = dartType(fld.type);
    const suffix = type === 'dynamic' || type.endsWith('?') || isOpt(fld.type) ? '' : '?';
    return '  final ' + type + suffix + ' ' + camel(n) + ';';
  }).join('\n');
  const ctorParams = fields.map((n) => '    this.' + camel(n) + ',').join('\n');
  const toJson = fields.map((n) => {
    const fld = schema.frames.flatMap((f) => f.fields).find((x) => x.name === n);
    const value = camel(n);
    return "    if (" + value + " != null) map['" + n + "'] = " + value + ";";
  }).join('\n');
  const fromJson = fields.map((n) => {
    const fld = schema.frames.flatMap((f) => f.fields).find((x) => x.name === n);
    let expr = "json['" + n + "']";
    if (isArray(fld.type)) expr = "(" + expr + " as List?)?.cast<" + dartType(fld.type).replace('List<', '').replace('>', '') + ">()";
    return '      ' + camel(n) + ': ' + expr + ',';
  }).join('\n');
  const helpers = schema.frames.map((f) => {
    const args = f.fields.map((fld) => dartType(fld.type) + (isOpt(fld.type) ? '' : '') + ' ' + camel(fld.name)).join(', ');
    const body = f.fields.map((fld) => '    ' + camel(fld.name) + ': ' + camel(fld.name) + ',').join('\n');
    return 'BusFrame ' + camel(f.kind) + 'Frame(' + args + ') => BusFrame(\n' +
      '    kind: ' + q(f.kind) + ',\n' + body + '\n  );\n';
  }).join('\n');
  return BANNER.dart +
    "import 'dart:convert';\n\n" +
    'const List<String> FRAME_KINDS = [' + kinds.map(q).join(', ') + '];\n\n' +
    errConsts + '\n\n' +
    'class BusFrame {\n' +
    '  final String kind;\n' + decls + '\n\n' +
    '  const BusFrame({\n    required this.kind,\n' + ctorParams + '\n  });\n\n' +
    '  Map<String, dynamic> toJson() {\n' +
    "    final map = <String, dynamic>{'kind': kind};\n" + toJson + '\n    return map;\n' +
    '  }\n\n' +
    '  static BusFrame fromJson(Map<String, dynamic> json) => BusFrame(\n' +
    "    kind: json['kind'] as String,\n" + fromJson + '\n  );\n' +
    '}\n\n' +
    'Map<String, dynamic> busError(String code, String message) => {\'code\': code, \'message\': message};\n\n' +
    'String encodeFrame(BusFrame frame) => jsonEncode(frame.toJson());\n\n' +
    'BusFrame decodeFrame(String line) {\n' +
    '  final json = jsonDecode(line) as Map<String, dynamic>;\n' +
    '  if (!FRAME_KINDS.contains(json[\'kind\'])) throw FormatException(\'E_BAD_FRAME\');\n' +
    '  return BusFrame.fromJson(json);\n' +
    '}\n\n' +
    helpers;
}

// ------------------------------------------------------------------ Dart runtime
function dartRuntime() {
  return BANNER.dart +
    "import 'dart:async';\n" +
    "import 'dart:convert';\n" +
    "import 'dart:io';\n\n" +
    "import 'protocol.dart';\n\n" +
    'class EndpointManifest {\n  final List<String> provides;\n  final List<String> subscribes;\n  const EndpointManifest(this.provides, this.subscribes);\n}\n\n' +
    'class RequestOutcome {\n  final dynamic result;\n  final Map<String, dynamic>? error;\n  const RequestOutcome(this.result, this.error);\n}\n\n' +
    'abstract class EndpointHooks {\n' +
    '  RequestOutcome onRequest(String capability, dynamic params, String correlationId);\n' +
    '  void onEvent(String topic, dynamic payload, String from);\n' +
    '}\n\n' +
    'EndpointRuntime? activeRuntime;\n\n' +
    'EndpointRuntime currentRuntime() {\n' +
    '  final runtime = activeRuntime;\n' +
    '  if (runtime == null) throw StateError("endpoint runtime is not started");\n' +
    '  return runtime;\n' +
    '}\n\n' +
    'class EndpointRuntime {\n' +
    '  final String endpointId;\n' +
    '  final EndpointHooks hooks;\n' +
    '  int counter = 0;\n' +
    '  final Map<String, Completer<dynamic>> pending = <String, Completer<dynamic>>{};\n\n' +
    '  EndpointRuntime(this.endpointId, this.hooks);\n\n' +
    '  void write(BusFrame frame) => stdout.writeln(encodeFrame(frame));\n\n' +
    '  void announce(List<String> provides, List<String> subscribes) => write(announceFrame(endpointId, provides, subscribes));\n' +
    '  void subscribe(String topic) => write(subscribeFrame(topic));\n' +
    '  void unsubscribe(String topic) => write(unsubscribeFrame(topic));\n' +
    '  void publish(String topic, dynamic payload) => write(publishFrame(topic, payload));\n' +
    '  void bye() => write(byeFrame(endpointId));\n' +
    '  void heartbeat() => write(publishFrame(\'event.heartbeat\', {\'endpointId\': endpointId}));\n\n' +
    '  Future<dynamic> request(String capability, dynamic params) {\n' +
    '    counter += 1;\n' +
    '    final id = endpointId + "-" + counter.toString();\n' +
    '    final completer = Completer<dynamic>();\n' +
    '    pending[id] = completer;\n' +
    '    write(requestFrame(id, capability, params));\n' +
    '    return completer.future;\n' +
    '  }\n\n' +
    '  void handle(String line) {\n' +
    '    BusFrame frame;\n' +
    '    try { frame = decodeFrame(line); } catch (_) { return; }\n' +
    '    switch (frame.kind) {\n' +
    '      case \'request\':\n' +
    '        try {\n' +
    '          final outcome = hooks.onRequest(frame.capability!, frame.params, frame.id!);\n' +
    '          write(responseFrame(frame.id!, outcome.result, outcome.error));\n' +
    '        } catch (err) {\n' +
    '          write(responseFrame(frame.id!, null, busError(eInternal, err.toString())));\n' +
    '        }\n' +
    '        break;\n' +
    '      case \'event\':\n' +
    '        hooks.onEvent(frame.topic!, frame.payload, frame.from!);\n' +
    '        break;\n' +
    '      case \'response\':\n' +
    '        final completer = pending.remove(frame.id);\n' +
    '        if (completer != null && !completer.isCompleted) {\n' +
    '          if (frame.error != null) completer.completeError(frame.error.toString());\n' +
    '          else completer.complete(frame.result);\n' +
    '        }\n' +
    '        break;\n' +
    '    }\n' +
    '  }\n\n' +
    '  Future<void> run() {\n' +
    '    final done = Completer<void>();\n' +
    '    stdin.transform(utf8.decoder).transform(const LineSplitter()).listen(\n' +
    '      (line) => handle(line),\n' +
    '      onDone: () { if (!done.isCompleted) done.complete(); },\n' +
    '      onError: (Object err) { if (!done.isCompleted) done.completeError(err); },\n' +
    '    );\n' +
    '    return done.future;\n' +
    '  }\n' +
    '}\n\n' +
    'String endpointIdFromEnv(List<String> args) {\n' +
    '  for (final arg in args) {\n' +
    '    if (arg.startsWith(\'--endpoint-id=\')) return arg.substring(\'--endpoint-id=\'.length);\n' +
    '  }\n' +
    '  final fromEnv = Platform.environment[\'LANIA_ENDPOINT_ID\'];\n' +
    '  return fromEnv ?? \'endpoint-\' + pid.toString();\n' +
    '}\n\n' +
    'Future<void> boot(EndpointManifest manifest, EndpointHooks hooks, List<String> args) async {\n' +
    '  final runtime = EndpointRuntime(endpointIdFromEnv(args), hooks);\n' +
    '  activeRuntime = runtime;\n' +
    '  runtime.announce(manifest.provides, manifest.subscribes);\n' +
    '  final raw = Platform.environment[\'LANIA_BRIDGE_HEARTBEAT_MS\'];\n' +
    '  if (raw != null) {\n' +
    '    final ms = int.tryParse(raw) ?? 0;\n' +
    '    if (ms > 0) Timer.periodic(Duration(milliseconds: ms), (_) => runtime.heartbeat());\n' +
    '  }\n' +
    '  try { await runtime.run(); } finally { runtime.bye(); }\n' +
    '}\n';
}

